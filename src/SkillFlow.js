/* SkillFlow.js — the SKILL FLOW CHART for staff (Head of School 2026-11-19: "a giant flow chart of little mini skills building on top
   of each other ... click on every step ... the objective ... the way the child is learning the skill ... where things are thin ...
   put him over here"). Read only. The data is SF_DATA (SkillFlowData.js, generated by tools/skill_flow.js from the live lessons).
   Each call adds live counts per skill: boys working on it now (started, not mastered) and boys who mastered it (TEST boys left out,
   same counts as the Course map, dmUse_). Placing a boy uses the Library's libApply 'place' (its own rules, undo and history).
   Subjects (HoS 2026-11-19): English, Math, Science, Limudei Kodesh.
   Calls (API_ALLOW): sfFlow. */
function sfFlow(token, subject) {
  sgStaff_(token);
  var D = typeof SF_DATA_JSON === 'string' ? JSON.parse(SF_DATA_JSON) : {};   /* stored as text (read only here; see tools/skill_flow.js) */
  var key = String(subject || 'ENGLISH').toUpperCase(); var F = D[key] || null;
  if (!F) throw new Error('No flow chart for that subject yet.');
  var use = {}; try { use = dmUse_(); } catch (e) {}
  var live = {}; F.nodes.forEach(function (n) { var u = use[n.id]; if (u) live[n.id] = [Math.max(0, u[0] - u[1]), u[1]]; });
  var subjects = Object.keys(D).filter(function (k) { return k !== 'built'; }).map(function (k) { return { key: k, title: D[k].title }; });
  return { built: D.built, subjects: subjects, flow: F, live: live };
}
